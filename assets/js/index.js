        let adsenseScriptLoaded = false;

        function qrPushAd(adContainer) {
            if (!adContainer || adContainer.dataset.adPushed === 'true') return;
            
            const ins = adContainer.querySelector('ins.adsbygoogle');
            if (!ins) return;

            // Verify element is rendered in viewport/layout with width > 0
            const rect = ins.getBoundingClientRect();
            const isVisible = rect.width > 0 && rect.height > 0 && window.getComputedStyle(adContainer).display !== 'none';

            if (isVisible) {
                // Defer push to next animation frame to guarantee layout completion
                requestAnimationFrame(() => {
                    if (adContainer.dataset.adPushed === 'true') return;
                    const currentRect = ins.getBoundingClientRect();
                    if (currentRect.width > 0) {
                        qrLoadAdSenseScript();
                        try {
                            (window.adsbygoogle = window.adsbygoogle || []).push({});
                            adContainer.dataset.adPushed = 'true';
                        } catch (e) {
                            console.error("AdSense push error:", e);
                        }
                    }
                });
            }
        }

        function qrCheckVisibleAds() {
            setTimeout(() => {
                document.querySelectorAll('.lazy-ad').forEach(ad => {
                    if (ad.dataset.adPushed !== 'true') {
                        qrPushAd(ad);
                    }
                });
            }, 150);
        }

        function qrInitLazyAdSense() {
            if ('IntersectionObserver' in window) {
                const adObserver = new IntersectionObserver((entries, observer) => {
                    entries.forEach(entry => {
                        if (entry.isIntersecting && entry.boundingClientRect.width > 0) {
                            const adElement = entry.target;
                            qrPushAd(adElement);
                            if (adElement.dataset.adPushed === 'true') {
                                observer.unobserve(adElement);
                            }
                        }
                    });
                }, { rootMargin: '100px 0px' });

                document.querySelectorAll('.lazy-ad').forEach(ad => {
                    adObserver.observe(ad);
                });
            } else {
                qrCheckVisibleAds();
            }
        }

        function qrLoadAdSenseScript() {
            if (adsenseScriptLoaded) return;
            adsenseScriptLoaded = true;
            
            const script = document.createElement('script');
            script.src = "https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=ca-pub-XXXXXXXXXXXXXXXX";
            script.async = true;
            script.crossOrigin = "anonymous";
            document.head.appendChild(script);
        }

        function qrToggleTheme() {
            document.body.classList.toggle('dark-mode');
            const isDark = document.body.classList.contains('dark-mode');
            document.getElementById('themeToggle').innerHTML = isDark ? '<i class="fas fa-sun"></i>' : '<i class="fas fa-moon"></i>';
            localStorage.setItem('qr_theme', isDark ? 'dark' : 'light');
        }

        function qrToggleLang() {
            const newLang = currentLang === 'ar' ? 'en' : 'ar';
            qrSetLanguage(newLang);
        }

        function qrSetLanguage(lang) {
            currentLang = lang;
            localStorage.setItem('qr_lang', lang);
            document.documentElement.lang = lang;
            document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
            document.getElementById('langToggle').innerText = lang === 'ar' ? 'EN' : 'العربية';

            document.querySelectorAll('[data-i18n]').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (translations[lang] && translations[lang][key]) {
                    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                        el.placeholder = translations[lang][key];
                    } else {
                        el.innerText = translations[lang][key];
                    }
                }
            });
        }

        function qrNav(targetId) {
            document.querySelectorAll('.section').forEach(sec => sec.classList.remove('active'));
            document.querySelectorAll('.nav-btn').forEach(btn => btn.classList.remove('active-nav'));

            const targetSection = document.getElementById(targetId);
            if (targetSection) targetSection.classList.add('active');

            const activeNavBtn = document.getElementById(`btn-nav-${targetId}`);
            if (activeNavBtn) activeNavBtn.classList.add('active-nav');

            if (targetId !== 'decoder' && isCameraActive) {
                qrStopCamera();
            }

            window.scrollTo({ top: 0, behavior: 'smooth' });

            // Trigger visible ad check after section becomes visible
            qrCheckVisibleAds();
        }

        async function qrStartCamera() {
            try {
                if (!html5QrCode) {
                    html5QrCode = new Html5Qrcode("reader");
                }
                const config = { fps: 10, qrbox: { width: 220, height: 220 } };
                
                await html5QrCode.start(
                    { facingMode: "environment" },
                    config,
                    (decodedText) => {
                        qrOnScanSuccess(decodedText);
                    },
                    () => {}
                );

                isCameraActive = true;
                const camBtnText = document.getElementById('camBtnText');
                if (camBtnText) camBtnText.innerText = translations[currentLang].btn_stop_cam;
                document.getElementById('camBtn').classList.replace('btn-primary', 'btn-secondary');
            } catch (err) {
                qrShowToast(translations[currentLang].toast_cam_error);
            }
        }

        async function qrStopCamera() {
            if (html5QrCode && isCameraActive) {
                try {
                    await html5QrCode.stop();
                    isCameraActive = false;
                    const camBtnText = document.getElementById('camBtnText');
                    if (camBtnText) camBtnText.innerText = translations[currentLang].btn_start_cam;
                    document.getElementById('camBtn').classList.replace('btn-secondary', 'btn-primary');
                } catch (err) {
                    console.error(err);
                }
            }
        }

        function qrDecodeFile(input) {
            if (input.files && input.files[0]) {
                const file = input.files[0];
                if (!html5QrCode) {
                    html5QrCode = new Html5Qrcode("reader");
                }
                html5QrCode.scanFile(file, true)
                    .then(decodedText => {
                        qrOnScanSuccess(decodedText);
                    })
                    .catch(() => {
                        document.getElementById('decodeResult').innerText = "لم يتم العثور على رمز QR في هذه الصورة.";
                    });
            }
        }

        function qrOnScanSuccess(decodedText) {
            currentDecodedText = decodedText;
            const resEl = document.getElementById('decodeResult');
            resEl.innerText = decodedText;

            document.getElementById('copyResultBtn').classList.remove('hidden');
            
            if (decodedText.startsWith('http://') || decodedText.startsWith('https://')) {
                document.getElementById('openLinkBtn').classList.remove('hidden');
            } else {
                document.getElementById('openLinkBtn').classList.add('hidden');
            }

            qrShowToast(translations[currentLang].toast_copied);
        }

        function qrCopyResult() {
            if (!currentDecodedText) return;
            qrCopyTextToClipboard(currentDecodedText);
        }

        function qrOpenResultLink() {
            if (currentDecodedText.startsWith('http://') || currentDecodedText.startsWith('https://')) {
                window.open(currentDecodedText, '_blank');
            }
        }

        function qrUpdateGenUI() {
            const qrTypeEl = document.getElementById('qrType');
            if (!qrTypeEl) return;
            const type = qrTypeEl.value;
            
            const simpleBox = document.getElementById('simpleBox');
            const wifiBox = document.getElementById('wifiBox');
            const vcardBox = document.getElementById('vcardBox');
            const waBox = document.getElementById('waBox');
            const emailBox = document.getElementById('emailBox');

            if (simpleBox) simpleBox.classList.add('hidden');
            if (wifiBox) wifiBox.classList.add('hidden');
            if (vcardBox) vcardBox.classList.add('hidden');
            if (waBox) waBox.classList.add('hidden');
            if (emailBox) emailBox.classList.add('hidden');

            if (type === 'url' || type === 'text') {
                if (simpleBox) simpleBox.classList.remove('hidden');
            } else if (type === 'wifi') {
                if (wifiBox) wifiBox.classList.remove('hidden');
            } else if (type === 'vcard') {
                if (vcardBox) vcardBox.classList.remove('hidden');
            } else if (type === 'whatsapp') {
                if (waBox) waBox.classList.remove('hidden');
            } else if (type === 'email') {
                if (emailBox) emailBox.classList.remove('hidden');
            }

            qrGenerateLive();
        }

        function qrBuildPayload() {
            const qrTypeEl = document.getElementById('qrType');
            if (!qrTypeEl) return "https://example.com";
            const type = qrTypeEl.value;
            
            if (type === 'url' || type === 'text') {
                const val = document.getElementById('qrInput').value.trim();
                return val || "https://example.com";
            } else if (type === 'wifi') {
                const ssid = document.getElementById('ssid').value.trim();
                const pass = document.getElementById('pass').value.trim();
                const enc = document.getElementById('encryption').value;
                if (!ssid) return "WIFI:S:MyNetwork;T:WPA;P:password;;";
                return `WIFI:S:${ssid};T:${enc};P:${pass};;`;
            } else if (type === 'vcard') {
                const first = document.getElementById('vcFirst').value.trim();
                const last = document.getElementById('vcLast').value.trim();
                const phone = document.getElementById('vcPhone').value.trim();
                const email = document.getElementById('vcEmail').value.trim();
                const company = document.getElementById('vcCompany').value.trim();
                
                return `BEGIN:VCARD\nVERSION:3.0\nN:${last};${first};;;\nFN:${first} ${last}\nTEL:${phone}\nEMAIL:${email}\nORG:${company}\nEND:VCARD`;
            } else if (type === 'whatsapp') {
                const phone = document.getElementById('waPhone').value.trim().replace(/[^0-9]/g, '');
                const msg = encodeURIComponent(document.getElementById('waMsg').value.trim());
                if (!phone) return "https://wa.me/";
                return `https://wa.me/${phone}${msg ? '?text=' + msg : ''}`;
            } else if (type === 'email') {
                const to = document.getElementById('emailTo').value.trim();
                const sub = encodeURIComponent(document.getElementById('emailSub').value.trim());
                const body = encodeURIComponent(document.getElementById('emailBody').value.trim());
                if (!to) return "mailto:example@domain.com";
                return `mailto:${to}?subject=${sub}&body=${body}`;
            }
            return "https://example.com";
        }

        function qrGenerateLive() {
            const payload = qrBuildPayload();
            const qrContainer = document.getElementById('qrcode');
            if (!qrContainer) return;
            qrContainer.innerHTML = "";

            const darkColorEl = document.getElementById('qrColorDark');
            const lightColorEl = document.getElementById('qrColorLight');

            const darkColor = darkColorEl ? darkColorEl.value : "#000000";
            const lightColor = lightColorEl ? lightColorEl.value : "#ffffff";

            try {
                qrCodeObj = new QRCode(qrContainer, {
                    text: payload,
                    width: 200,
                    height: 200,
                    colorDark: darkColor,
                    colorLight: lightColor,
                    correctLevel: QRCode.CorrectLevel.H
                });
            } catch (err) {
                console.error("QR Generation error:", err);
            }
        }

        function qrDownloadPNG() {
            const canvas = document.querySelector('#qrcode canvas');
            const img = document.querySelector('#qrcode img');
            let dataUrl = "";

            if (canvas) {
                dataUrl = canvas.toDataURL("image/png");
            } else if (img) {
                dataUrl = img.src;
            }

            if (!dataUrl) {
                qrShowToast(translations[currentLang].toast_no_content);
                return;
            }

            const link = document.createElement('a');
            link.download = `qrcode_${Date.now()}.png`;
            link.href = dataUrl;
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);

            qrShowToast(translations[currentLang].toast_downloading);
        }

        function qrCopyImage() {
            const canvas = document.querySelector('#qrcode canvas');
            if (!canvas) {
                qrShowToast(translations[currentLang].toast_no_content);
                return;
            }

            canvas.toBlob(blob => {
                try {
                    const item = new ClipboardItem({ "image/png": blob });
                    navigator.clipboard.write([item]).then(() => {
                        qrShowToast(translations[currentLang].toast_copied);
                    });
                } catch (err) {
                    qrShowToast(translations[currentLang].toast_copied);
                }
            });
        }

        function qrCopyTextToClipboard(text) {
            const textArea = document.createElement("textarea");
            textArea.value = text;
            document.body.appendChild(textArea);
            textArea.select();
            try {
                document.execCommand('copy');
                qrShowToast(translations[currentLang].toast_copied);
            } catch (err) {
                console.error('Copy failed', err);
            }
            document.body.removeChild(textArea);
        }

        function qrShowToast(msg) {
            const toast = document.getElementById('toast');
            document.getElementById('toastMsg').innerText = msg;
            toast.classList.add('show');
            setTimeout(() => {
                toast.classList.remove('show');
            }, 3000);
        }

        function qrSubmitContact(e) {
            e.preventDefault();
            document.getElementById('contactName').value = "";
            document.getElementById('contactEmail').value = "";
            document.getElementById('contactMsg').value = "";
            qrShowToast(translations[currentLang].toast_sent);
        }

