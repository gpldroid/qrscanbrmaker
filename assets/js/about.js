        let currentLang = 'ar';

        window.addEventListener('DOMContentLoaded', () => {
            // Theme Init
            const savedTheme = localStorage.getItem('qr_theme');
            if (savedTheme === 'dark' || (!savedTheme && window.matchMedia('(prefers-color-scheme: dark)').matches)) {
                document.body.classList.add('dark-mode');
                document.getElementById('themeToggle').innerHTML = '<i class="fas fa-sun"></i>';
            }

            // Language Init
            const savedLang = localStorage.getItem('qr_lang') || 'ar';
            qrSetLanguage(savedLang);

            // Cookies Banner Init
            if (localStorage.getItem('qr_cookies_accepted') === null) {
                document.getElementById('cookieBanner').style.display = 'block';
            }

            // Scroll Back To Top Listener
            window.addEventListener('scroll', () => {
                const btt = document.getElementById('backToTop');
                if (window.scrollY > 250) {
                    btt.classList.add('visible');
                } else {
                    btt.classList.remove('visible');
                }
            });

            qrInitLazyAdSense();
        });

        let adsenseScriptLoaded = false;

        function qrPushAd(adContainer) {
            if (!adContainer || adContainer.dataset.adPushed === 'true') return;
            const ins = adContainer.querySelector('ins.adsbygoogle');
            if (!ins) return;

            const rect = ins.getBoundingClientRect();
            if (rect.width > 0 && rect.height > 0) {
                requestAnimationFrame(() => {
                    if (adContainer.dataset.adPushed === 'true') return;
                    qrLoadAdSenseScript();
                    try {
                        (window.adsbygoogle = window.adsbygoogle || []).push({});
                        adContainer.dataset.adPushed = 'true';
                    } catch (e) {
                        console.error("AdSense push error:", e);
                    }
                });
            }
        }

        function qrInitLazyAdSense() {
            if ('IntersectionObserver' in window) {
                const observer = new IntersectionObserver((entries) => {
                    entries.forEach(entry => {
                        if (entry.isIntersecting) {
                            qrPushAd(entry.target);
                            observer.unobserve(entry.target);
                        }
                    });
                }, { rootMargin: '100px 0px' });

                document.querySelectorAll('.lazy-ad').forEach(ad => observer.observe(ad));
            } else {
                document.querySelectorAll('.lazy-ad').forEach(ad => qrPushAd(ad));
            }
        }

        function qrLoadAdSenseScript() {
            if (adsenseScriptLoaded) return;
            adsenseScriptLoaded = true;
            const script = document.createElement('script');
            script.src = "https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=ca-pub-XXXXXXXXXXXXXXXX";
            script.async = true;
            script.crossOrigin = "anonymous";
            document.head.appendChild(script);
        }

        function qrToggleTheme() {
            document.body.classList.toggle('dark-mode');
            const isDark = document.body.classList.contains('dark-mode');
            document.getElementById('themeToggle').innerHTML = isDark ? '<i class="fas fa-sun"></i>' : '<i class="fas fa-moon"></i>';
            localStorage.setItem('qr_theme', isDark ? 'dark' : 'light');
        }

        function qrToggleLang() {
            const newLang = currentLang === 'ar' ? 'en' : 'ar';
            qrSetLanguage(newLang);
        }

        function qrSetLanguage(lang) {
            currentLang = lang;
            localStorage.setItem('qr_lang', lang);
            document.documentElement.lang = lang;
            document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
            document.getElementById('langToggle').innerText = lang === 'ar' ? 'EN' : 'العربية';

            document.querySelectorAll('[data-i18n]').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (translations[lang] && translations[lang][key]) {
                    el.innerText = translations[lang][key];
                }
            });
        }

        function toggleAccordion(btn) {
            const item = btn.parentElement;
            item.classList.toggle('active');
        }

        function qrAcceptCookies() {
            localStorage.setItem('qr_cookies_accepted', 'true');
            document.getElementById('cookieBanner').style.display = 'none';
        }

        function qrRejectCookies() {
            localStorage.setItem('qr_cookies_accepted', 'false');
            document.getElementById('cookieBanner').style.display = 'none';
        }


